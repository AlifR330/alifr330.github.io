function initDate() {
  const days   = ['Minggu','Senin','Selasa','Rabu','Kamis','Jumat','Sabtu'];
  const months = ['Januari','Februari','Maret','April','Mei','Juni',
                  'Juli','Agustus','September','Oktober','November','Desember'];
  const now = new Date();
  document.getElementById('live-date').textContent =
    `${days[now.getDay()]}, ${now.getDate()} ${months[now.getMonth()]} ${now.getFullYear()}`;
}

// ─── MODAL ARTIKEL ──────────────────────────────────────────────

function openArticle(idx) {
  const a = articles[idx];
  document.getElementById('m-tag').textContent  = a.tag;
  document.getElementById('m-title').textContent = a.title;
  document.getElementById('m-meta').textContent  = `Oleh ${a.author} · ${a.date} · ${a.read} baca`;
  document.getElementById('m-body').innerHTML    = a.body;
  document.getElementById('modal').classList.add('open');
  document.body.style.overflow = 'hidden';
}

function closeModal(e) {
  if (e.target === document.getElementById('modal')) closeModalDirect();
}

function closeModalDirect() {
  document.getElementById('modal').classList.remove('open');
  document.body.style.overflow = '';
}

// ─── MODAL LOGIN ─────────────────────────────────────────────────

